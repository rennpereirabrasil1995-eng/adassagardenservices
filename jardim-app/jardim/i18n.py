def translate(key, lang, **kwargs):
    table = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANGUAGE])
    text = table.get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)  # cai pro inglês, ou mostra a chave crua
    return text.format(**kwargs) if kwargs else text


